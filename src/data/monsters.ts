// Monster manifest (SPEC-v2 §8). Ids, names, levels, families, sizes, elements, ranks, essences and echo marks
// are fixed by the spec table. Combat stats come from monsterStats(level, rank) (src/core/balance.ts) nudged
// within ±20% for flavour: constructs and sylvans are tanky, sprites and swarms fragile, fiends and hunters hit
// hard. EXP and coins stay at the baseline.
//
// Conventions:
// - radius: S 12-14 · M 15-18 · L elites 24-30 · wardens 34-40. Speed 30-90 px/s (the player walks at 150).
// - respawn: commons 8-15 s · elites 180 s · the rare Moonmoth 240 s · wardens 600 s (after defeatedAt).
// - techniques: cooldown 3-9 s; `range` = distance at which the monster starts the technique. Echo techniques
//   start within 190 px so a cast aimed at the player is always inside the 6-tile witness radius.
//   Echo marks: commons/elites 3, the rare Moonmoth 5, wardens 1. `mon_*` attacks are never learnable.
//   Wardens add a monster-only enrage technique below 50 % HP.
// - Elites built on a common species reuse its texture (`base`, `texture`, multiply `tint`, `scale` 1.3-1.4);
//   every other species draws its own `mon_<id>` texture (src/game/art/monsters.ts).
// - Material drops stay at or below 25 %; tomes, shards and relics are `once` (only while not yet owned).

interface Flavour {
  hp?: number;
  atk?: number;
  def?: number;
}

/** `base × mult`, rounded but never outside base ±20 % (matters for single-digit DEF). */
function nudge(base: number, mult = 1): number {
  const v = Math.round(base * mult);
  return Math.min(Math.floor(base * 1.2), Math.max(Math.ceil(base * 0.8), v));
}

/** Baseline stats for (level, rank) with a ±20 % flavour nudge on HP / ATK / DEF. */
function stats(level: number, rank: MonsterRank, f: Flavour = {}) {
  const base = monsterStats(level, rank);
  return {
    level,
    rank,
    hp: nudge(base.hp, f.hp),
    atk: nudge(base.atk, f.atk),
    def: nudge(base.def, f.def),
    exp: base.exp,
    coins: base.coins,
  };
}

